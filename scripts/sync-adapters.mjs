/**
 * Write or drift-check all generated adapter files under `rootDir`.
 */
export function syncAdapters({ rootDir = DEFAULT_ROOT, check = false } = {}) {
  const adapters = buildAdapterFiles();
  const drifted = [];
  const written = [];

  for (const { relPath, content } of adapters) {
    const absPath = path.join(rootDir, relPath);
    const expected = normalizeLineEndings(content);

    if (check) {
      if (!fs.existsSync(absPath)) {
        drifted.push(`${relPath} (missing)`);
        continue;
      }
      const actual = normalizeLineEndings(fs.readFileSync(absPath, "utf8"));
      if (actual !== expected) {
        drifted.push(`${relPath} (out of sync)`);
      }
      continue;
    }

    fs.mkdirSync(path.dirname(absPath), { recursive: true });
    const existing = fs.existsSync(absPath)
      ? normalizeLineEndings(fs.readFileSync(absPath, "utf8"))
      : null;
    if (existing !== expected) {
      fs.writeFileSync(absPath, expected, "utf8");
      written.push(relPath);
    }
  }

  return {
    ok: drifted.length === 0,
    total: adapters.length,
    drifted,
    written,
  };
}

function parseCliArgs(argv) {
  let check = false;
  let rootDir = DEFAULT_ROOT;

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") {
      check = true;
    } else if (arg === "--root") {
      const nextVal = argv[i + 1];
      if (!nextVal) {
        throw new Error("--root requires a directory argument");
      }
      rootDir = path.resolve(nextVal);
      i += 1;
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }

  return { check, rootDir };
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  try {
    const { check, rootDir } = parseCliArgs(process.argv.slice(2));
    const result = syncAdapters({ rootDir, check });

    if (check) {
      if (!result.ok) {
        console.error(
          `Adapter sync check failed (${result.drifted.length}/${result.total} drifted):\n` +
            result.drifted.map((item) => `  - ${item}`).join("\n") +
            "\nRun `npm run sync:adapters` to regenerate."
        );
        process.exitCode = 1;
      } else {
        console.log(`Adapter sync check passed (${result.total}/${result.total} up to date).`);
      }
    } else {
      console.log(
        `Adapter sync complete (${result.total} managed files, ${result.written.length} updated).`
      );
    }
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exitCode = 1;
  }
}
